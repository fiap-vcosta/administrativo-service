DO $do$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'administrativo_app') THEN
    CREATE ROLE administrativo_app NOLOGIN NOSUPERUSER INHERIT NOCREATEDB NOCREATEROLE NOREPLICATION;
  END IF;
END
$do$;

REVOKE CONNECT ON DATABASE administrativo FROM PUBLIC;
GRANT CONNECT ON DATABASE administrativo TO administrativo_app;

REVOKE CONNECT ON DATABASE template1 FROM PUBLIC;

GRANT USAGE, CREATE ON SCHEMA public TO administrativo_app;
GRANT ALL ON ALL TABLES IN SCHEMA public TO administrativo_app;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO administrativo_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO administrativo_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO administrativo_app;
